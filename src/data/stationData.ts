export function formatDriveTime(minutes: number | null): string {
  if (!minutes) return "—";
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  if (h === 0) return `${m} min`;
  if (m === 0) return `${h} hr`;
  return `${h} hr ${m} min`;
}

export function getDistanceZone(km: number | null): "near" | "short" | "medium" | "long" | "far" {
  if (!km) return "near";
  if (km < 50) return "near";
  if (km < 90) return "short";
  if (km < 130) return "medium";
  if (km < 175) return "long";
  return "far";
}

